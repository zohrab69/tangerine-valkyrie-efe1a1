#!/usr/bin/env bash
# Writes /opt/jarvis/Caddyfile from /opt/jarvis/.env and /opt/jarvis/ui-auth.hash.
# Always: n8n site. With a screen password + VOICE_SECRET: also the JARVIS screen site.
set -euo pipefail
APP=${APP:-/opt/jarvis}
N8N_HOST=$(grep '^N8N_HOST=' "$APP/.env" | cut -d= -f2)
VOICE_SECRET=$(grep '^VOICE_SECRET=' "$APP/.env" | cut -d= -f2 || true)
JARVIS_HOST="jarvis.${N8N_HOST#n8n.}"
umask 077
{
  echo "# Generated by caddy-config.sh - do not edit by hand, re-run the script instead."
  echo "$N8N_HOST {"
  echo "  reverse_proxy n8n:5678"
  echo "}"
  if [ -s "$APP/ui-auth.hash" ] && [ -n "$VOICE_SECRET" ]; then
    HASH=$(cat "$APP/ui-auth.hash")
    cat <<CADDY

$JARVIS_HOST {
  basic_auth {
    owner $HASH
  }
  header {
    -Server
    X-Frame-Options DENY
    X-Content-Type-Options nosniff
    Referrer-Policy no-referrer
    Permissions-Policy "microphone=(self), camera=()"
  }
  handle /api/health {
    rewrite * /healthz
    reverse_proxy n8n:5678
  }
  handle /api/ask {
    rewrite * /webhook/jarvis-voice
    reverse_proxy n8n:5678 {
      header_up -Authorization
      header_up X-Jarvis-Key $VOICE_SECRET
    }
  }
  handle {
    root * /srv/jarvis-ui
    file_server
  }
}
CADDY
  fi
} > "$APP/Caddyfile"
chmod 644 "$APP/Caddyfile"   # read by the caddy container; contains only a password HASH and the n8n webhook key
echo "Caddyfile written (screen site: $([ -s "$APP/ui-auth.hash" ] && [ -n "$VOICE_SECRET" ] && echo "https://$JARVIS_HOST" || echo none yet))"
