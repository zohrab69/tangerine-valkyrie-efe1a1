# STEP 3 - Start the n8n sandbox stack NEXT TO your existing n8n.
#
# Does NOT touch your n8n container, port 5678 or the n8n_data volume.
# Refuses to run unless a verified backup from today exists.
#
#   * Generates unique secrets into infra\stack\*.env (only if missing - re-running
#     never changes existing secrets).
#   * Starts sandbox-certs, sandbox-api, sandbox-runner-1 on network "jarvis-net".
#   * Waits for sandbox-api to be healthy and the runner to register.
#
# Run from the jarvis folder:
#   powershell -ExecutionPolicy Bypass -File .\infra\windows\03-setup-sandbox.ps1
#   (add -WithSearch to also start SearXNG web search, ~150-300 MB RAM)

param([switch]$WithSearch, [switch]$SkipBackupCheck)

. (Join-Path $PSScriptRoot '_common.ps1')
Assert-Docker

Write-Step 'Safety checks'
$latest = Get-LatestBackup
if (-not $SkipBackupCheck) {
    if (-not $latest -or $latest.LastWriteTime -lt (Get-Date).Date) {
        throw 'No backup from today in jarvis-backups. Run .\infra\windows\02-backup.ps1 first.'
    }
    Write-Ok "Backup found: $($latest.Name)"
}
$os = Get-CimInstance Win32_OperatingSystem
$freeGb = [math]::Round($os.FreePhysicalMemory / 1MB, 1)
Write-Ok "Free Windows RAM: $freeGb GB"
if ($freeGb -lt 1.5) { throw 'Less than 1.5 GB RAM free. Close apps/browser tabs and try again (protects against a frozen laptop).' }

Write-Step 'Secrets (generated once, kept on this computer only)'
$envPath    = Join-Path $StackDir '.env'
$apiPath    = Join-Path $StackDir 'sandbox-api.env'
$runnerPath = Join-Path $StackDir 'sandbox-runner.env'
$n8nPath    = Join-Path $StackDir 'n8n.env'

if ((Test-Path $apiPath) -and (Read-EnvValue $apiPath 'SANDBOX_API_KEYS')) {
    Write-Ok 'sandbox-api.env already exists - keeping existing secrets'
    $apiKey = Read-EnvValue $apiPath 'SANDBOX_API_KEYS'
} else {
    $apiKey = New-Secret; $regToken = New-Secret; $runnerKey = New-Secret
    Write-EnvFile $apiPath @(
        '# Generated by 03-setup-sandbox.ps1. Never commit or share.',
        "SANDBOX_API_KEYS=$apiKey",
        "SANDBOX_API_RUNNER_REGISTRATION_TOKEN=$regToken",
        "SANDBOX_API_RUNNER_API_KEY=$runnerKey")
    Write-EnvFile $runnerPath @(
        '# Generated by 03-setup-sandbox.ps1. Never commit or share.',
        "SANDBOX_RUNNER_REGISTRATION_TOKEN=$regToken",
        "SANDBOX_RUNNER_API_KEYS=$runnerKey")
    Write-Ok 'Created sandbox-api.env and sandbox-runner.env'
}
if (-not (Test-Path $envPath)) { Copy-Item (Join-Path $StackDir '.env.example') $envPath; Write-Ok 'Created .env' }
$sx = Read-EnvValue $envPath 'SEARXNG_SECRET'
if (-not $sx -or $sx -eq 'generated-by-setup-script') { Set-EnvValue $envPath 'SEARXNG_SECRET' (New-Secret) }
if (-not (Test-Path $n8nPath) -or -not (Read-EnvValue $n8nPath 'N8N_SANDBOX_SERVICE_API_KEY')) {
    Copy-Item (Join-Path $StackDir 'n8n.env.example') $n8nPath
    Set-EnvValue $n8nPath 'N8N_SANDBOX_SERVICE_API_KEY' $apiKey
    Write-Ok 'Created n8n.env (used only if you later do Path B)'
}

Write-Step 'Validating compose file'
Invoke-Compose @('config', '--quiet')
Write-Ok 'compose.yml is valid'

Write-Step 'Downloading sandbox images (first time: several minutes, ~1 GB)'
$profileArgs = @(); if ($WithSearch) { $profileArgs = @('--profile', 'search') }
Invoke-Compose ($profileArgs + @('pull', 'sandbox-api', 'sandbox-runner-1'))

Write-Step 'Starting sandbox (n8n is not started or changed by this)'
$services = @('sandbox-certs', 'sandbox-api', 'sandbox-runner-1'); if ($WithSearch) { $services += 'searxng' }
Invoke-Compose ($profileArgs + @('up', '-d') + $services)

Write-Step 'Waiting for sandbox-api to become healthy'
$healthy = $false
for ($i = 0; $i -lt 60; $i++) {
    $state = & docker inspect -f '{{.State.Health.Status}}' jarvis-sandbox-api-1
    if ($state -eq 'healthy') { $healthy = $true; break }
    Start-Sleep -Seconds 3
}
if (-not $healthy) {
    Write-Bad 'sandbox-api did not become healthy within 3 minutes. Logs:'
    Invoke-Compose @('logs', '--tail', '60', 'sandbox-certs', 'sandbox-api')
    exit 1
}
Write-Ok 'sandbox-api is healthy'

Start-Sleep -Seconds 10
$ErrorActionPreference = 'Continue'   # docker logs writes to stderr; don't treat that as an error
$runnerLog = (& docker logs --tail 200 jarvis-sandbox-api-1 2>&1 | Out-String)
$ErrorActionPreference = 'Stop'
if ($runnerLog -match '(?i)runner') { Write-Ok 'Runner activity found in sandbox-api logs' }
else { Write-Warn2 'No runner registration seen yet. Check later with: docker compose logs sandbox-api | findstr /i runner' }
if ((& docker inspect -f '{{.State.Running}}' jarvis-sandbox-runner-1) -ne 'true') {
    Write-Bad 'sandbox-runner-1 is not running:'
    Invoke-Compose @('logs', '--tail', '60', 'sandbox-runner-1')
    exit 1
}
Write-Ok 'sandbox-runner-1 is running'

& docker stats --no-stream --format 'table {{.Name}}\t{{.MemUsage}}'
Write-Host "`nNext: .\infra\windows\04-connect-n8n.ps1" -ForegroundColor Cyan
